"""Generate the README architecture diagram.

Run `python3 docs/architecture.py` after editing REGIONS or BOUNDARIES;
it rewrites docs/architecture.svg. The diagram paints its own background
so it reads the same under any GitHub theme or OS color scheme.
"""
from pathlib import Path

W = 600
PAD = 16
BOX_X, BOX_W, BOX_H = 176, 330, 40
GAP, BOUNDARY_GAP = 40, 76
AX = BOX_X + BOX_W / 2

# Regions: (label lines, [(name, detail, payload on the arrow leaving this box)])
REGIONS = [
    (["Replayer", "process"], [
        ("ITCH sample file", "one trading day", "length-prefixed ITCH messages"),
        ("Replayer", "optional packet loss", "MoldUDP64 packets"),
    ]),
    (["Ingest", "thread"], [
        ("Receiver", "sequencing, gap detection", "ITCH messages, in order"),
        ("Decoder", "ITCH 5.0, zero-copy", "decoded message structs"),
        ("Normalizer", "locate code to instrument", "normalized events"),
    ]),
    (["Book", "thread"], [
        ("Order book", "L3 to L2 / L1", "top-of-book updates"),
        ("Consumers", "snapshots, stats, latency", None),
    ]),
]
BOUNDARIES = ["UDP multicast", "SPSC ring buffer"]

COLORS = dict(ink="#1f2328", muted="#59636e", rule="#8c959f", box="#ffffff",
              border="#d0d7de")

SANS = "-apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans', Helvetica, Arial, sans-serif"
MONO = "ui-monospace, SFMono-Regular, 'SF Mono', Menlo, Consolas, monospace"


def arrow(o, t, y1, y2):
    o.append(f'<line x1="{AX}" y1="{y1}" x2="{AX}" y2="{y2 - 1}" stroke="{t["ink"]}" '
             f'stroke-width="1.25" marker-end="url(#a)"/>')


def label(o, t, y, text):
    o.append(f'<text x="{AX + 12}" y="{y}" font-family="{MONO}" font-size="11.5" '
             f'fill="{t["muted"]}">{text}</text>')


def render(t):
    o, y = [], PAD
    for r, (region_label, boxes) in enumerate(REGIONS):
        top = y
        for i, (name, detail, payload) in enumerate(boxes):
            o.append(f'<rect x="{BOX_X}" y="{y}" width="{BOX_W}" height="{BOX_H}" rx="3" '
                     f'fill="{t["box"]}" stroke="{t["ink"]}" stroke-width="1.25"/>')
            o.append(f'<text x="{BOX_X + 14}" y="{y + 25}" font-size="14" font-weight="600" '
                     f'fill="{t["ink"]}">{name}</text>')
            o.append(f'<text x="{BOX_X + BOX_W - 14}" y="{y + 25}" font-size="12.5" '
                     f'text-anchor="end" fill="{t["muted"]}">{detail}</text>')
            last_in_region = i == len(boxes) - 1
            if payload is None:
                y += BOX_H
                break
            if not last_in_region:
                arrow(o, t, y + BOX_H, y + BOX_H + GAP)
                label(o, t, y + BOX_H + GAP / 2 + 4, payload)
                y += BOX_H + GAP
            else:
                gy = y + BOX_H
                line_y = gy + BOUNDARY_GAP / 2
                arrow(o, t, gy, gy + BOUNDARY_GAP)
                label(o, t, gy + 22, payload)
                o.append(f'<line x1="{PAD}" y1="{line_y}" x2="{W - PAD}" y2="{line_y}" '
                         f'stroke="{t["rule"]}" stroke-dasharray="4 4"/>')
                o.append(f'<text x="{W - PAD}" y="{line_y + 17}" text-anchor="end" '
                         f'font-family="{MONO}" font-size="11.5" fill="{t["muted"]}">'
                         f'{BOUNDARIES[r]}</text>')
                y = gy + BOUNDARY_GAP
        bottom = y if payload is None else y - BOUNDARY_GAP
        # Region bracket and label in the left column.
        bx = BOX_X - 20
        o.append(f'<path d="M{bx + 6} {top} H{bx} V{bottom} H{bx + 6}" fill="none" '
                 f'stroke="{t["rule"]}" stroke-width="1.25"/>')
        for k, line in enumerate(region_label):
            o.append(f'<text x="{bx - 12}" y="{top + 17 + k * 17}" text-anchor="end" '
                     f'font-size="13" fill="{t["muted"]}">{line}</text>')
    h = y + PAD
    head = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{h}" '
        f'viewBox="0 0 {W} {h}" role="img" aria-label="Feed handler architecture">',
        "<!-- Generated by docs/architecture.py. Edit that script, not this file. -->",
        f'<defs><marker id="a" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="8" '
        f'markerHeight="8" markerUnits="userSpaceOnUse" orient="auto">'
        f'<path d="M0 1 L10 5 L0 9 z" fill="{t["ink"]}"/></marker></defs>',
        f'<rect x="0.5" y="0.5" width="{W - 1}" height="{h - 1}" rx="6" '
        f'fill="{t["box"]}" stroke="{t["border"]}"/>',
        f'<g font-family="{SANS}">',
    ]
    return "\n".join(head + o + ["</g></svg>"]) + "\n"


(Path(__file__).parent / "architecture.svg").write_text(render(COLORS))
